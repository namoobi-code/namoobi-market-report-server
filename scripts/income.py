def main():
    key = _key()
    years = list(range(2016, datetime.now().year))
    S = {}
    got = []
    for y in years:
        rows = fetch(y, key)
        if not rows:
            continue
        got.append(y)
        acc = {}
        for r in rows:
            c = r["C1"]
            a = acc.setdefault(c, {"nm": r["C1_NM"]})
            a[(r["C2"], r["ITM_ID"])] = float(r["DT"])
        for c, a in acc.items():
            n = a.get(("B02", "T001"))
            amt = a.get(("B02", "T002"))
            tax = a.get(("B04", "T002"))
            if not n or not amt or not c.startswith("A") or len(c) != 5:
                continue
            s = S.setdefault(c, {"nm": a["nm"], "sido": SIDO_PREFIX.get(c[:3], c[:3]), "avg": {}, "n": {}, "tax": {}})
            s["avg"][str(y)] = round(amt * 100 / n)          # 백만원 → 만원/인
            s["n"][str(y)] = int(n)
            if tax:
                s["tax"][str(y)] = round(tax * 100 / n)
        print(f"  {y}: 시군구 {len(acc)}")
        time.sleep(0.4)
    if not S:
        raise SystemExit("✗ 수집 0")
    last = str(got[-1])
    vals = sorted(v["avg"][last] for v in S.values() if last in v["avg"])
    import bisect
    pct = {c: round(100 * bisect.bisect_left(vals, v["avg"][last]) / max(1, len(vals) - 1)) for c, v in S.items() if last in v["avg"]}
    out = {"asof": datetime.now().strftime("%Y-%m-%d %H:%M"), "years": got, "last": last,
           "src": "국세청 국세통계 · 시군구별 근로소득 연말정산 신고현황(주소지) — KOSIS 133 DT_133001N_4215",
           "note": "1인당 평균 총급여(만원) = 과세대상근로소득 ÷ 신고인원. 근로소득만이라 사업·금융소득이 큰 지역은 과소. 시군구 단위(성남·용인은 시 전체).",
           "sgg": S, "pct": pct, "luxmen": LUX}
    OUT.write_text(json.dumps(out, ensure_ascii=False, separators=(",", ":")), encoding="utf-8")
    top = sorted(((v["avg"][last], v["sido"], v["nm"]) for v in S.values() if last in v["avg"]), reverse=True)[:6]
    print(f"  → {OUT} ({OUT.stat().st_size//1024}KB) · {got[0]}~{last} · 시군구 {len(S)} · {last} 상위: " + " · ".join(f"{s} {n} {a:,}" for a, s, n in top))


if __name__ == "__main__":
    main()
